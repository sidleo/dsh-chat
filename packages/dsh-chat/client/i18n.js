/**
 * 绑定一个命名空间的翻译函数。
 *
 * @param locale - DSH client 的 locale 服务。
 * @returns (key) => string。
 */
export function bindTranslator(locale) {
  const dictionary = { zh, en };
  return (key) => {
    const language = locale?.getSnapshot?.()?.locale ?? 'zh';
    const table = dictionary[language] ?? zh;
    return table[key] ?? zh[key] ?? key;
  };
}
